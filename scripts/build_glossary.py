#!/usr/bin/env python3
"""Build glossary.qmd from the "Key Terms" section of every chapter. Built by Claude, 11/19/2026

Quarto runs this automatically before each render (see `pre-render` in
_quarto.yml). Each chapter's Key Terms section should be a definition list:

    ## Key Terms

    **Matter**
    : Anything that has mass and takes up space.

Do not edit glossary.qmd by hand; edit the Key Terms in the chapters instead.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "glossary.qmd"
SKIP_DIRS = {"_book", ".quarto", ".git", ".github", "scripts"}

HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*(\{.*\})?\s*$")
TITLE = re.compile(r"^title:\s*[\"']?(.*?)[\"']?\s*$")


def chapter_title(lines, fallback):
    """Return the title from the file's YAML front matter."""
    if lines and lines[0].strip() == "---":
        for line in lines[1:]:
            if line.strip() == "---":
                break
            match = TITLE.match(line)
            if match:
                return match.group(1)
    return fallback


def key_terms(lines):
    """Yield (term, definition) pairs from the Key Terms section."""
    in_section = False
    section_level = 0
    in_code = False
    term = None

    for line in lines:
        stripped = line.strip()
        if stripped.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue

        heading = HEADING.match(line)
        if heading:
            level = len(heading.group(1))
            if heading.group(2).strip().lower() == "key terms":
                in_section, section_level, term = True, level, None
                continue
            if in_section and level <= section_level:
                break
        if not in_section:
            continue
        if stripped.startswith(":::"):
            break

        if stripped.startswith(":") and term:
            definition = stripped.lstrip(":").strip()
            if definition:
                yield term, definition
        elif stripped:
            term = stripped.strip("*_ ").strip()


def main():
    entries = {}
    for path in sorted(ROOT.rglob("*.qmd")):
        rel = path.relative_to(ROOT)
        if path == OUTPUT or SKIP_DIRS.intersection(rel.parts):
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        title = chapter_title(lines, rel.stem)
        for term, definition in key_terms(lines):
            entries.setdefault(term.lower(), []).append(
                (term, definition, title, rel.as_posix())
            )

    out = [
        "---",
        'title: "Glossary"',
        "---",
        "",
        "<!-- This file is generated by scripts/build_glossary.py. Do not edit it",
        "     by hand; edit the Key Terms section of each chapter instead. -->",
        "",
    ]

    current_letter = None
    for key in sorted(entries):
        letter = key[0].upper() if key[0].isalpha() else "#"
        if letter != current_letter:
            current_letter = letter
            out += [f"## {letter} {{.unnumbered}}", ""]

        uses = entries[key]
        if len({d.lower() for _, d, _, _ in uses}) > 1:
            print(f"glossary: '{uses[0][0]}' has different definitions in "
                  f"{', '.join(p for *_, p in uses)}", file=sys.stderr)

        out.append(f"**{uses[0][0]}**")
        seen = set()
        for _, definition, title, rel in uses:
            if definition.lower() in seen:
                continue
            seen.add(definition.lower())
            sources = "; ".join(
                f"[{t}]({p})" for _, d, t, p in uses if d.lower() == definition.lower()
            )
            out.append(f": {definition} *(See {sources}.)*")
        out.append("")

    if not entries:
        out.append("*No key terms yet.*")

    text = "\n".join(out).rstrip() + "\n"
    # Only write when something changed, so `quarto preview` doesn't loop.
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"glossary: wrote {len(entries)} terms to glossary.qmd")


if __name__ == "__main__":
    main()